from typing import Protocol
from ..contracts import Episode, Example, Memory, Support, Task, Transition


class TaskEnvironment(Protocol):
    def reset(self, task: Task) -> str: ...
    def step(self, action: str) -> Transition: ...
    def close(self) -> None: ...


class EvidenceVerifier(Protocol):
    def verify_support(self, memory: Memory, episode: Episode, support: Support) -> bool: ...
    def verify_example(self, example: Example, episode: Episode) -> bool: ...
